-- =============================================================================
-- VENUS POS - PostgreSQL Schema (auto-applied idempotently on server startup)
-- Replaces Supabase. Every business table carries a NOT NULL user_id FK and all
-- access is isolated at the application layer: every query filters by the
-- authenticated user_id taken from the verified JWT (never from the request).
-- Conventions per Postgres best practices:
--   * bigint GENERATED ALWAYS AS IDENTITY primary keys
--   * text (not varchar), numeric(12,2) for money, timestamptz for time
--   * every FK indexed, composite indexes led by user_id
--   * short transactions with SELECT ... FOR UPDATE for balance mutations
-- =============================================================================

-- -----------------------------------------------------------------------------
-- users: subscribers + admins (replaces Supabase auth.users + profiles)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email         TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    full_name     TEXT NOT NULL DEFAULT '',
    role          TEXT NOT NULL DEFAULT 'subscriber' CHECK (role IN ('subscriber', 'admin')),
    is_approved   BOOLEAN NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -----------------------------------------------------------------------------
-- sim_inventory: barcode-batched SIM stock, strictly per subscriber
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sim_inventory (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    barcode        TEXT NOT NULL,
    operator       TEXT NOT NULL CHECK (operator IN ('Zain', 'Asiacell', 'زين', 'آسياسيل')),
    batch_name     TEXT NOT NULL DEFAULT '',
    purchase_price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (purchase_price >= 0),
    selling_price  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (selling_price >= 0),
    reward         NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (reward >= 0),
    status         TEXT NOT NULL DEFAULT 'in_stock' CHECK (status IN ('in_stock', 'sold')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    sold_at        TIMESTAMPTZ,
    UNIQUE (user_id, barcode)
);

-- -----------------------------------------------------------------------------
-- sim_sales: immutable sale ledger; profit = (selling_price + reward) - purchase_price
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sim_sales (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    sim_id         BIGINT REFERENCES sim_inventory(id) ON DELETE SET NULL,
    barcode        TEXT NOT NULL,
    operator       TEXT NOT NULL,
    purchase_price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (purchase_price >= 0),
    selling_price  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (selling_price >= 0),
    reward         NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (reward >= 0),
    profit         NUMERIC(12,2) NOT NULL DEFAULT 0,
    notes          TEXT NOT NULL DEFAULT '',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -----------------------------------------------------------------------------
-- credit_sales: recharge card sales; profit generated by the database
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS credit_sales (
    id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    operator      TEXT NOT NULL CHECK (operator IN ('Zain', 'Asiacell', 'زين', 'آسياسيل')),
    category      TEXT NOT NULL DEFAULT '',
    cost_price    NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (cost_price >= 0),
    selling_price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (selling_price >= 0),
    profit        NUMERIC(12,2) GENERATED ALWAYS AS (selling_price - cost_price) STORED,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -----------------------------------------------------------------------------
-- debt_contracts: customer debt book (دفتر الديون)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS debt_contracts (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    debtor_name  TEXT NOT NULL,
    phone        TEXT NOT NULL DEFAULT '',
    description  TEXT NOT NULL DEFAULT '',
    total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount > 0),
    paid_amount  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    status       TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed')),
    due_date     DATE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (paid_amount <= total_amount)
);

-- -----------------------------------------------------------------------------
-- debt_payments: immutable installment ledger with exact balance snapshots
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS debt_payments (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    contract_id      BIGINT NOT NULL REFERENCES debt_contracts(id) ON DELETE CASCADE,
    amount           NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    previous_balance NUMERIC(12,2) NOT NULL CHECK (previous_balance >= 0),
    remaining_amount NUMERIC(12,2) NOT NULL CHECK (remaining_amount >= 0),
    note             TEXT NOT NULL DEFAULT '',
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

